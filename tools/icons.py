"""Writes src/lib/icons.ts: Phosphor (MIT) icons as SVG path data.

Usage: python3 -I tools/icons.py   (from the project folder, standard library only)
Add a name to ICONS (Phosphor's own kebab-case name) and run it again.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE / 'phosphor'))
from glyphs import Font, path  # noqa: E402

ICONS = sorted(set('''
arrow-up-right arrow-right arrow-left caret-right caret-down check envelope-simple github-logo linkedin-logo x-logo
google-play-logo app-store-logo star sun moon list x map-pin graduation-cap trophy certificate briefcase
device-mobile robot globe code browser flow-arrow chat-circle-text lightning file-text download-simple
copy check-circle sparkle stack database cloud users shield-check film-strip subtitles clipboard-text scan
car storefront chart-bar plant read-cv-logo house
'''.split()))


def main():
    names = json.loads((HERE / 'phosphor/names.json').read_text())
    font = Font(str(HERE / 'phosphor/PhosphorRegular.ttf'))
    lines, missing = [], []
    for name in ICONS:
        cp = names.get(name)
        gid = font.cmap.get(int(cp, 16)) if cp else None
        if gid is None:
            missing.append(name)
            continue
        lines.append(f"  '{name}': '{path(font, font.contours(gid))}',")
    if missing:
        sys.exit('No Phosphor icon called: ' + ', '.join(missing))
    out = HERE.parent / 'src/lib/icons.ts'
    out.write_text(
        '// Generated by tools/icons.py from Phosphor Regular (MIT). Do not edit by hand.\n'
        '// Each value is SVG path data in a 256 unit box.\n'
        'export const icons = {\n' + '\n'.join(lines) + '\n} as const;\n\n'
        'export type IconName = keyof typeof icons;\n')
    print(len(ICONS), 'icons written to', out)


main()
